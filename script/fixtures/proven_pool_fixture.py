#!/usr/bin/env python3
"""Capture a real mainnet fixture for ProvenPoolPrice tests: one block's header RLP, the PoolManager's account proof and the
storage proof of pool 0xb07d's slot0 at that block, written as Solidity constants (test/fixtures/ProvenPoolFixture.sol).

Usage: RPC=<archive rpc> python3 script/fixtures/proven_pool_fixture.py [block]
The header is re-encoded from eth_getBlockByNumber and must hash to the block's hash (checked here), so the fixture is
exactly what a keeper sends. Nothing is sent anywhere but the RPC; no key is used."""
import json, os, subprocess, sys, urllib.request

RPC = os.environ["RPC"]
MANAGER = "0x000000000004444c5dc75cB358380D2e3dE08A90"
POOL_ID = "0xb07d640fd9e2eb9dc81b953c8e4fd006bdfeaf276010fb5418eb763ca15abfb3"
POOLS_SLOT = 6
HEADER_FIELDS = [  # Ethereum block header field order (through Prague's requestsHash)
    "parentHash", "sha3Uncles", "miner", "stateRoot", "transactionsRoot", "receiptsRoot", "logsBloom", "difficulty",
    "number", "gasLimit", "gasUsed", "timestamp", "extraData", "mixHash", "nonce", "baseFeePerGas", "withdrawalsRoot",
    "blobGasUsed", "excessBlobGas", "parentBeaconBlockRoot", "requestsHash",
]
INTS = {"difficulty", "number", "gasLimit", "gasUsed", "timestamp", "baseFeePerGas", "blobGasUsed", "excessBlobGas"}


def rpc(method, params):
    body = json.dumps({"jsonrpc": "2.0", "id": 1, "method": method, "params": params}).encode()
    req = urllib.request.Request(RPC, body, {"content-type": "application/json"})
    out = json.load(urllib.request.urlopen(req, timeout=60))
    if "error" in out:
        raise SystemExit(f"{method}: {out['error']}")
    return out["result"]


def rlp_bytes(b: bytes) -> bytes:
    if len(b) == 1 and b[0] < 0x80:
        return b
    return _len(len(b), 0x80) + b


def rlp_list(items) -> bytes:
    payload = b"".join(items)
    return _len(len(payload), 0xC0) + payload


def _len(n, offset):
    if n <= 55:
        return bytes([offset + n])
    nb = n.to_bytes((n.bit_length() + 7) // 8, "big")
    return bytes([offset + 55 + len(nb)]) + nb


def keccak(hexdata: str) -> str:
    return subprocess.run(["cast", "keccak", hexdata], capture_output=True, text=True, check=True).stdout.strip()


def header_rlp(block) -> bytes:
    items = []
    for f in HEADER_FIELDS:
        if f not in block or block[f] is None:
            break  # older forks end earlier; fields are only ever appended
        v = block[f]
        if f in INTS:
            n = int(v, 16)
            items.append(rlp_bytes(b"" if n == 0 else n.to_bytes((n.bit_length() + 7) // 8, "big")))
        else:
            items.append(rlp_bytes(bytes.fromhex(v[2:])))
    return rlp_list(items)


def main():
    n = int(sys.argv[1]) if len(sys.argv) > 1 else int(rpc("eth_blockNumber", []), 16) - 2
    block = rpc("eth_getBlockByNumber", [hex(n), False])
    h = header_rlp(block)
    got = keccak("0x" + h.hex())
    if got.lower() != block["hash"].lower():
        raise SystemExit(f"header re-encoding does not hash to the block: {got} != {block['hash']} (a new header field?)")
    slot = keccak("0x" + bytes.fromhex(POOL_ID[2:]).hex() + POOLS_SLOT.to_bytes(32, "big").hex())
    proof = rpc("eth_getProof", [MANAGER, [slot], hex(n)])
    sp = proof["storageProof"][0]
    word = int(sp["value"], 16)
    sqrtp = word & ((1 << 160) - 1)

    def arr(name, nodes):
        lines = [f"    function {name}() internal pure returns (bytes[] memory p) {{", f"        p = new bytes[]({len(nodes)});"]
        lines += [f'        p[{i}] = hex"{x[2:]}";' for i, x in enumerate(nodes)]
        return "\n".join(lines + ["    }"])

    sol = f"""// SPDX-License-Identifier: MIT
pragma solidity 0.8.26;

/// @dev GENERATED by script/fixtures/proven_pool_fixture.py from mainnet block {n} (do not edit). Header RLP hashes to the
/// block's hash; proofs are eth_getProof(PoolManager, [slot0 of pool 0xb07d]) at that block.
library ProvenPoolFixture {{
    uint256 internal constant BLOCK = {n};
    bytes32 internal constant BLOCK_HASH = {block['hash']};
    uint256 internal constant TIMESTAMP = {int(block['timestamp'], 16)};
    bytes32 internal constant STATE_ROOT = {block['stateRoot']};
    bytes32 internal constant SLOT0_KEY = {slot};
    uint256 internal constant SLOT0_WORD = {hex(word)};
    uint160 internal constant SQRT_PRICE_X96 = {sqrtp};

    function header() internal pure returns (bytes memory) {{
        return hex"{h.hex()}";
    }}

{arr("accountProof", proof["accountProof"])}

{arr("storageProof", sp["proof"])}
}}
"""
    out = os.path.join(os.path.dirname(__file__), "..", "..", "test", "fixtures", "ProvenPoolFixture.sol")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, "w").write(sol)
    print(f"block {n} hash ok; sqrtPriceX96 {sqrtp}; account nodes {len(proof['accountProof'])}, storage nodes {len(sp['proof'])} -> {os.path.normpath(out)}")


main()
